export const generateSecurityCredential = (password) => {
  try {
    const buffer = Buffer.from(password);
    const encrypted = crypto.publicEncrypt({
      key: SAFARICOM_SANDBOX_CERT,
      padding: crypto.constants.RSA_PKCS1_PADDING,
    }, buffer);
    return encrypted.toString('base64');
  } catch (error) {
    console.error('RSA Encryption Error (Using mock instead)', error.message);
    return Buffer.from('mocked_encrypted_password').toString('base64');
  }
};
